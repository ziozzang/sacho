CREATE SCHEMA sacho;
CREATE TABLE sacho.schema_migrations(version BIGINT PRIMARY KEY);
INSERT INTO sacho.schema_migrations VALUES(1);
CREATE TABLE sacho.items(
 id TEXT PRIMARY KEY, spec TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'unknown',
 last_check BIGINT, latency_ms BIGINT, failures BIGINT NOT NULL DEFAULT 0,
 successes BIGINT NOT NULL DEFAULT 0, revision BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE sacho.checks(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id TEXT NOT NULL REFERENCES sacho.items(id) ON DELETE CASCADE,
 at BIGINT NOT NULL, status TEXT NOT NULL, latency_ms BIGINT NOT NULL,
 output TEXT NOT NULL, detail TEXT NOT NULL, metric_value DOUBLE PRECISION, display_value TEXT
);
CREATE INDEX checks_time ON sacho.checks(item_id,at);
CREATE TABLE sacho.incidents(
 id TEXT PRIMARY KEY, item_id TEXT REFERENCES sacho.items(id) ON DELETE SET NULL,
 name TEXT NOT NULL, status TEXT NOT NULL, opened_at BIGINT NOT NULL,
 resolved_at BIGINT, detail TEXT NOT NULL
);
CREATE INDEX incidents_time ON sacho.incidents(opened_at);
CREATE TABLE sacho.subscribers(
 id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, token TEXT UNIQUE NOT NULL,
 verified BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
);
CREATE TABLE sacho.webhooks(
 id TEXT PRIMARY KEY, name TEXT NOT NULL, url TEXT NOT NULL, enabled BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE sacho.outbox(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL, destination TEXT NOT NULL, payload TEXT NOT NULL,
 attempts BIGINT NOT NULL DEFAULT 0, next_at BIGINT NOT NULL, delivered_at BIGINT,
 error TEXT, created_at BIGINT NOT NULL
);
CREATE INDEX outbox_due ON sacho.outbox(next_at) WHERE delivered_at IS NULL;
CREATE TABLE sacho.settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE sacho.remote_runs(
 item_id TEXT PRIMARY KEY REFERENCES sacho.items(id) ON DELETE CASCADE,
 run_id TEXT NOT NULL UNIQUE, worker TEXT NOT NULL, revision BIGINT NOT NULL,
 lease_until BIGINT NOT NULL, result_hash TEXT
);
